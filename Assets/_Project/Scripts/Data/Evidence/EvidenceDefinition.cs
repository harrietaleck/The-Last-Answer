using System;
using UnityEngine;

namespace TLA.Data.Evidence
{
    /// <summary>What kind of evidence an item is. Decides how the inspect view presents it.</summary>
    public enum EvidenceCategory
    {
        Document = 0,     // read pages of text (reports, letters, contracts)
        Photograph = 1,   // look at an image and its caption
        Object = 2,       // a physical item collected from the scene
        Digital = 3,      // footage, logs, files on a screen
        Forensic = 4      // lab results, prints, samples
    }

    /// <summary>
    /// When an item can be found. All conditions must be met. Empty = available from the start.
    /// Checked by EvidenceService (C#), never by AI.
    /// </summary>
    [Serializable]
    public sealed class DiscoveryConditions
    {
        [Tooltip("These items must be collected first.")]
        public EvidenceDefinition[] requiresCollected = Array.Empty<EvidenceDefinition>();

        [Tooltip("These items must be examined first (Examine in the inspect or evidence screen).")]
        public EvidenceDefinition[] requiresExamined = Array.Empty<EvidenceDefinition>();

        [Tooltip("These facts must be established first.")]
        public CaseFact[] requiresFacts = Array.Empty<CaseFact>();

        [Tooltip("Hide the object completely until the conditions are met. Unticked = it can be looked at, but shows the hint below.")]
        public bool hiddenUntilAvailable;

        [Tooltip("Prompt while locked, e.g. \"Search cabinet\".")]
        public string lockedPrompt = "Search";

        [TextArea(1, 3)]
        [Tooltip("Shown when the player tries it too early, e.g. \"You don't know what you're looking for yet.\"")]
        public string lockedHint = "Nothing stands out yet.";

        public bool IsEmpty =>
            (requiresCollected == null || requiresCollected.Length == 0) &&
            (requiresExamined == null || requiresExamined.Length == 0) &&
            (requiresFacts == null || requiresFacts.Length == 0);
    }

    /// <summary>A relationship between two items the player can discover by connecting them.</summary>
    [Serializable]
    public sealed class EvidenceConnection
    {
        [Tooltip("The other item. A connection only needs to be defined on ONE of the two items.")]
        public EvidenceDefinition other;

        [TextArea(2, 4)]
        [Tooltip("What connecting them reveals, shown to the player.")]
        public string explanation = "";

        [Tooltip("Fact established when the connection is made (optional).")]
        public CaseFact establishesFact;
    }

    /// <summary>
    /// One piece of evidence: everything the game needs to place, show, examine and reason about it.
    /// Authored by hand (or by the CaseDataBuilder for test content); never generated by AI.
    /// The player's progress with it (collected, examined, presented) lives in EvidenceService.
    /// Create via Assets → Create → The Last Answer → Evidence → Evidence.
    /// </summary>
    [CreateAssetMenu(fileName = "EVD_New", menuName = "The Last Answer/Evidence/Evidence", order = 30)]
    public sealed class EvidenceDefinition : ScriptableObject
    {
        [Header("Identity")]
        [Tooltip("Stable id used by code, dialogue reactions and save files, e.g. \"EVD_CCTV\". Never change after release.")]
        public string evidenceId = "EVD_New";

        public string displayName = "New evidence";

        public EvidenceCategory category = EvidenceCategory.Document;

        [TextArea(2, 4)]
        [Tooltip("One or two sentences shown in the evidence list and detail view.")]
        public string description = "";

        [Tooltip("Where it was found, e.g. \"Evidence Room · investigation desk\".")]
        public string locationFound = "";

        [Header("Inspect view")]
        [Tooltip("Verb shown in the world, e.g. \"Read case file\". Becomes \"[E] Read case file\".")]
        public string interactionPrompt = "Inspect";

        [TextArea(4, 14)]
        [Tooltip("Documents and digital items: the text, one entry per page. Photos/objects: optional extra text.")]
        public string[] pages = Array.Empty<string>();

        [Tooltip("Photo or object image (optional; a placeholder frame is shown without one).")]
        public Sprite image;

        [TextArea(1, 3)]
        [Tooltip("Caption under the image, e.g. \"Rear door, taken 00:40\".")]
        public string caption = "";

        [Header("Examination")]
        [TextArea(2, 6)]
        [Tooltip("What a closer look reveals. Hidden until the player examines the item.")]
        public string examinationNotes = "";

        [Tooltip("Facts this item establishes once examined.")]
        public CaseFact[] relatedFacts = Array.Empty<CaseFact>();

        [Header("Collection")]
        [Tooltip("Ticked: the object is taken (disappears from the scene). Unticked: it's logged as evidence but stays in place (e.g. a wall board).")]
        public bool collectable = true;

        [TextArea(1, 3)]
        [Tooltip("Notebook entry written when collected (optional).")]
        public string noteOnCollect = "";

        [Tooltip("New objective when collected (optional; empty = unchanged).")]
        public string objectiveOnCollect = "";

        [Header("Discovery")]
        public DiscoveryConditions discovery = new DiscoveryConditions();

        [Header("Connections")]
        [Tooltip("Other items this one can be connected with in the evidence screen.")]
        public EvidenceConnection[] connections = Array.Empty<EvidenceConnection>();

        /// <summary>"DOCUMENT", "PHOTOGRAPH"…</summary>
        public string CategoryLabel => CategoryName(category);

        public static string CategoryName(EvidenceCategory c)
        {
            switch (c)
            {
                case EvidenceCategory.Document: return "DOCUMENT";
                case EvidenceCategory.Photograph: return "PHOTOGRAPH";
                case EvidenceCategory.Object: return "OBJECT";
                case EvidenceCategory.Digital: return "DIGITAL";
                default: return "FORENSIC";
            }
        }
    }
}
